/**
 * The NHL scorecard: plays the calibration set (N games of two overall-70 teams, and N of a 76 against a 66), puts each
 * total and "looks like hockey" measure beside the NHL's value and our target band (scripts/nhl-reference.ts), prints
 * the table and writes it to docs/superpowers/reviews/engine-scorecard-<label>.md.
 * Usage: npm run scorecard -- --label <label> [--games 300]
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { runGames, summarise, winShare, type Summary } from '../test/helpers';
import { NHL_REFERENCE, type Reference } from './nhl-reference';
import type { PlayMeasures } from '../test/measures';

const TOTALS = ['goals', 'shots', 'attempts', 'savePct', 'hits', 'blocks', 'takeaways', 'giveaways', 'faceoffsTotal'] as const;
type TotalKey = (typeof TOTALS)[number];

/** Our value of a reference row's measure. */
function oursOf(summary: Summary, favouriteWinShare: number, key: string): number {
  if (key === 'favouriteWinShare') return favouriteWinShare;
  if ((TOTALS as readonly string[]).includes(key)) return summary[key as TotalKey];
  if (key in summary.play) return summary.play[key as keyof PlayMeasures];
  throw new Error(`scorecard: no measure for reference key ${key}`);
}

/** One row per reference: our value, the reference, and whether ours is inside its band (ends included). */
export function scorecardRows(summary: Summary, favouriteWinShare: number): { key: string; ours: number; ref: Reference; inBand: boolean }[] {
  return NHL_REFERENCE.map((ref) => {
    const ours = oursOf(summary, favouriteWinShare, ref.key);
    return { key: ref.key, ours, ref, inBand: ours >= ref.band[0] && ours <= ref.band[1] };
  });
}

/** A value to 3 decimals below 1, else 2 (1 above 100). */
function num(x: number): string {
  if (!Number.isFinite(x)) return String(x);
  const a = Math.abs(x);
  return x.toFixed(a === 0 ? 0 : a < 1 ? 3 : a < 100 ? 2 : 1);
}

function band(b: [number, number]): string {
  if (b[1] === Infinity) return `${num(b[0])} or more`;
  if (b[0] === 0 && b[1] <= 0.001) return '0';
  if (b[0] === 0) return `${num(b[1])} or less`;
  return `${num(b[0])} to ${num(b[1])}`;
}

function sourceCell(r: Reference): string {
  const season = r.season === null ? '' : `, ${r.season}`;
  return `${r.source}${season}${r.verified || r.nhl === null ? '' : ' (from memory, unverified)'}`;
}

/** The scorecard as Markdown. */
export function scorecardMarkdown(o: { label: string; games: number; summary: Summary; favouriteWinShare: number; date: string }): string {
  const rows = scorecardRows(o.summary, o.favouriteWinShare);
  const esc = (s: string): string => s.replace(/\|/g, '\\|');
  const lines: string[] = [];
  lines.push(`# Engine scorecard: ${o.label}`, '');
  lines.push(`${o.date}. ${o.games} games of two overall-70 teams (fresh rosters every game) and ${o.games} of a 76 against a 66, the calibration set (\`runGames\`). Totals are per team per game unless the unit says otherwise; our games are 60 minutes of 5-on-5. Generated by \`npm run scorecard -- --label ${o.label} --games ${o.games}\`.`, '');
  const unverified = rows.filter((r) => r.ref.nhl !== null && !r.ref.verified).length;
  if (unverified > 0) lines.push(`**${unverified} NHL numbers are from memory, unverified**: the league's statistics pages could not be reached when this file was built. Check them before reading this as a comparison (see \`packages/engine/scripts/nhl-reference.ts\`).`, '');
  lines.push(`In band: ${rows.filter((r) => r.inBand).length} of ${rows.length}.`, '');
  lines.push('| measure | ours | NHL | band | in/out | unit | source and season |', '|---|---:|---:|---|---|---|---|');
  for (const r of rows) {
    const nhl = r.ref.nhl === null ? 'n/a' : `${num(r.ref.nhl)}${r.ref.verified ? '' : ' (unverified)'}`;
    lines.push(`| ${esc(r.ref.label)} (\`${r.key}\`) | ${num(r.ours)} | ${nhl} | ${band(r.ref.band)} | ${r.inBand ? 'in' : 'OUT'} | ${esc(r.ref.unit)} | ${esc(sourceCell(r.ref))} |`);
  }
  const referenced = new Set(rows.map((r) => r.key));
  const rest = (Object.keys(o.summary.play) as (keyof PlayMeasures)[]).filter((k) => !referenced.has(k));
  lines.push('', '## Other measures (no band)', '', '| measure | ours |', '|---|---:|');
  for (const k of rest) lines.push(`| \`${k}\` | ${num(o.summary.play[k])} |`);
  for (const k of ['faceoffs', 'offsides', 'icings', 'battles'] as const) lines.push(`| \`${k}\` per team per game | ${num(o.summary[k])} |`);
  lines.push(`| \`offsidesTotal\` per game | ${num(o.summary.offsidesTotal)} |`, `| \`icingsTotal\` per game | ${num(o.summary.icingsTotal)} |`);
  lines.push(`| \`tieShare\` | ${num(o.summary.tieShare)} |`, `| \`msPerGame\` (with the observer, on worker threads) | ${num(o.summary.msPerGame)} |`);
  return `${lines.join('\n')}\n`;
}

function main(): void {
  const argv = process.argv;
  const at = (name: string): string | undefined => { const i = argv.indexOf(`--${name}`); return i >= 0 ? argv[i + 1] : undefined; };
  const label = at('label');
  if (label === undefined || !/^[a-z0-9][a-z0-9-]*$/.test(label)) throw new Error('--label <label> is required (lower case, digits and dashes)');
  const games = Number(at('games') ?? 300);
  if (!Number.isInteger(games) || games <= 0) throw new Error('--games needs a positive whole number');
  const summary = summarise(runGames(games));
  const favouriteWinShare = winShare(runGames(games, { homeOverall: 76, awayOverall: 66 })).home;
  const md = scorecardMarkdown({ label, games, summary, favouriteWinShare, date: new Date().toISOString().slice(0, 10) });
  console.log(md);
  const out = resolve(fileURLToPath(new URL('../../../docs/superpowers/reviews/', import.meta.url)), `engine-scorecard-${label}.md`);
  writeFileSync(out, md);
  console.log(`written to ${out}`);
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
